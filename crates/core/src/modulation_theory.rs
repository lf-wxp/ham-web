/// 要点。
pub const MOD_TIPS: &[&str] = &[
  "同一种信息（话音）用不同调制方式，占用带宽与所需功率差别很大：SSB 最省带宽与功率，FM 最费带宽但抗噪最好。",
  "AM 的“功率利用率”指信息功率占总功率的比例，100% 调制时也只有 1/3，故同等信息功率下 SSB 明显更省电（常记作效率约高 4 倍 / 6 dB）。",
  "调制指数决定占用带宽：AM 过调制会产生谐波与邻道干扰，FM 频偏过大同样会超出允许带宽。",
  "用「带宽」与「信噪比」两个维度比较调制方式，就能理解为何 HF 远距离用 SSB、VHF 本地用 FM。",
];

