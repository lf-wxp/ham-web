#[cfg(test)]
mod tests {
  use super::*;

  #[test]
  fn meters_data_populated() {
    assert!(METERS.len() >= 7);
    for (name, target, usage) in METERS {
      assert!(!name.is_empty());
      assert!(!target.is_empty());
      assert!(!usage.is_empty());
    }
  }
}
