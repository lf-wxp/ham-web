#[cfg(test)]
mod tests {
  use super::*;

  fn connector(name: &str) -> &'static (&'static str, &'static str, &'static str) {
    CONNECTORS
      .iter()
      .find(|(n, ..)| n.contains(name))
      .unwrap_or_else(|| panic!("连接器表里缺少 {name}"))
  }

  #[test]
  fn connector_and_cable_data_populated() {
    assert!(CONNECTORS.len() >= 8);
    assert!(CABLES.len() >= 6);
    assert!(!SELECTION_TIPS.is_empty());
    assert!(!INSTALL_TIPS.is_empty());
    assert!(!FAULTS.is_empty());
    for (name, spec, notes) in CONNECTORS {
      assert!(!name.is_empty() && !spec.is_empty() && !notes.is_empty());
    }
    for (name, structure, advice) in CABLES {
      assert!(!name.is_empty() && !structure.is_empty() && !advice.is_empty());
    }
  }

  /// UHF 接头是历史叫法、不按恒阻抗设计：频率上限必须远低于 N 型、SMA 这类精密接头。
  #[test]
  fn uhf_connector_limit_is_far_below_precision_connectors() {
    assert!(connector("PL-259").1.contains("300 MHz"));
    assert!(connector("N 型").1.contains("11 GHz"));
    assert!(connector("SMA").1.contains("18 GHz"));
  }

  /// 阻抗必须逐条写明：接头混用 50 / 75 Ω 是考试与实作的高频错误。
  #[test]
  fn every_connector_states_its_impedance() {
    for (name, spec, _) in CONNECTORS {
      if name.contains("RCA") {
        // RCA 是反例条目：要显式说明它不是射频接头，不写阻抗。
        assert!(spec.contains("非射频"), "RCA 必须写明不是射频接头：{spec}");
        continue;
      }
      assert!(spec.contains('Ω'), "{name} 的阻抗列应写出 Ω：{spec}");
    }
    let f_type = connector("F 型");
    assert!(f_type.1.contains("75"));
    assert!(f_type.2.contains("50 Ω"), "F 型必须提醒不能用于 50 Ω 系统");
  }

  /// 受潮是馈线失效的首因：安装要点里必须有防水、故障表里必须有受潮。
  #[test]
  fn waterproofing_is_covered() {
    assert!(INSTALL_TIPS.iter().any(|s| s.contains("防水")));
    assert!(FAULTS.iter().any(|s| s.contains("受潮")));
  }
}
