#[cfg(test)]
mod tests {
  use super::*;

  #[test]
  fn coordination_data_populated() {
    assert!(COORDINATION_CONCEPTS.len() >= 4);
    assert!(COORDINATION_TIERS.len() >= 4);
    assert!(COORDINATION_STEPS.len() >= 4);
    assert!(INTERFERENCE_STEPS.len() >= 4);
    assert!(!COORDINATION_TIPS.is_empty());
  }

  #[test]
  fn band_diffs_cover_key_hf_and_vhf_bands() {
    assert!(IARU_BAND_DIFFS.len() >= 6);
    for band in ["160m", "80m", "40m", "6m", "2m", "70cm"] {
      assert!(
        IARU_BAND_DIFFS.iter().any(|(b, _, _)| *b == band),
        "缺少 {band} 的区际差异"
      );
    }
    // 每行三列都应有内容，便于表格渲染。
    for (band, r1, r23) in IARU_BAND_DIFFS {
      assert!(!band.is_empty() && !r1.is_empty() && !r23.is_empty());
    }
  }
}
