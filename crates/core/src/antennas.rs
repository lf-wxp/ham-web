#[cfg(test)]
mod tests {
  use super::*;

  #[test]
  fn antennas_have_svg_and_meta() {
    assert!(!ANTENNAS.is_empty());
    for a in ANTENNAS {
      assert!(!a.name.is_empty());
      assert!(!a.abbr.is_empty());
      assert!(!a.svg.is_empty());
      assert!(!a.gain.is_empty());
      assert!(!a.usage.is_empty());
      assert!(!a.desc.is_empty());
    }
  }

  /// 别把「哪些型式算常见」交给下一个人去猜：这里钉住考试口径的全集，
  /// 少一类就在这里红掉，而不是等用户翻页面时发现「怎么没有螺旋天线」。
  #[test]
  fn antennas_cover_every_common_type() {
    let abbrs: Vec<&str> = ANTENNAS.iter().map(|a| a.abbr).collect();
    for want in [
      "DP",
      "FoldDP",
      "VDP",
      "Inv-V",
      "EFHW",
      "GP",
      "Whip",
      "J-Pole",
      "YAGI",
      "LPDA",
      "Dish",
      "Helix",
      "Array",
      "Loop",
      "MagLoop",
      "K9AY",
      "LongWire",
      "T2FD",
      "Rhombic",
      "Beverage",
      "Isotropic",
    ] {
      assert!(abbrs.contains(&want), "缺少天线型式：{want}");
    }

    // 缩写是卡片上的身份标识，重复会让「哪张是哪张」失去依据。
    let mut sorted = abbrs.clone();
    sorted.sort_unstable();
    sorted.dedup();
    assert_eq!(sorted.len(), abbrs.len(), "天线缩写不能重复");
  }

  #[test]
  fn antenna_theory_populated() {
    assert!(ANTENNA_THEORY.len() >= 5);
    // 近场边界公式与 G/T 口径应在要点中出现。
    assert!(ANTENNA_THEORY.iter().any(|(_, d)| d.contains("2D²/λ")));
    assert!(ANTENNA_THEORY.iter().any(|(_, d)| d.contains("dB/K")));
  }
}
