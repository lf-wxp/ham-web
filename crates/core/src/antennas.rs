//! 常见业余天线型式速查：名称、缩写、增益参考、典型用途、简述与示意简图（SVG 内联内容）。
//!
//! 收录范围是**考试口径的常见型式**：术语表「天线」类里作为独立型式给出的条目、题库与
//! 方案库（实用天线 / 天线 DIY / `.nec` 模板）里出现过的型式，再加增益基准各向同性天线。
//! 收录与否只看「这种型式在考试与站内资料里出现过吗」，不做百科式罗列。

/// 一种天线型式。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct AntennaType {
  pub name: &'static str,
  pub abbr: &'static str,
  /// 增益参考（dBi，随结构/频率变化，仅作量级参考）。
  pub gain: &'static str,
  /// 典型用途。
  pub usage: &'static str,
  pub desc: &'static str,
  /// SVG 内联内容（不含外层 `<svg>`），viewBox 为 `0 0 100 60`。
  pub svg: &'static str,
}

#[allow(clippy::too_many_arguments)]
const fn antenna(
  name: &'static str,
  abbr: &'static str,
  gain: &'static str,
  usage: &'static str,
  desc: &'static str,
  svg: &'static str,
) -> AntennaType {
  AntennaType {
    name,
    abbr,
    gain,
    usage,
    desc,
    svg,
  }
}

