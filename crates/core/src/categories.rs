/// 按分类码查找二级分类。
#[must_use]
pub fn sub_category(code: &str) -> Option<&'static SubCategory> {
  SUB_CATEGORIES.iter().find(|s| s.code == code)
}

/// 按 key 查找一级分类。
#[must_use]
pub fn top_category(key: &str) -> Option<&'static TopCategory> {
  TOP_CATEGORIES.iter().find(|c| c.key == key)
}

/// 分类码（`p_code`）对应的一级分类，如 `"1.1.1"` → 法规。
#[must_use]
pub fn top_of(code: &str) -> Option<&'static TopCategory> {
  let sub = sub_category(code)?;
  top_category(sub.top)
}

/// 分类码对应的知识点。
#[must_use]
pub fn sub_note(code: &str) -> Option<&'static str> {
  SUB_NOTES.iter().find(|(c, _)| *c == code).map(|(_, n)| *n)
}

/// 一级分类的参考资料。
#[must_use]
pub fn top_refs(key: &str) -> &'static [RefItem] {
  TOP_REFS
    .iter()
    .find(|(k, _)| *k == key)
    .map_or(&[], |(_, r)| r)
}

/// 某一级分类下去重后的子类名称（保持定义顺序）。
#[must_use]
pub fn sub_names_of(top_key: &str) -> Vec<&'static str> {
  let mut names: Vec<&'static str> = Vec::new();
  for s in SUB_CATEGORIES.iter().filter(|s| s.top == top_key) {
    if !names.contains(&s.name) {
      names.push(s.name);
    }
  }
  names
}

/// 某一级分类下的分类码（P 码，保持定义顺序，去重）。
#[must_use]
pub fn sub_codes_of(top_key: &str) -> Vec<&'static str> {
  let mut codes: Vec<&'static str> = Vec::new();
  for s in SUB_CATEGORIES.iter().filter(|s| s.top == top_key) {
    if !codes.contains(&s.code) {
      codes.push(s.code);
    }
  }
  codes
}

