//! 题库分类体系：一级分类（题目类型）+ 二级分类（官方分类码 P → 大类/子类）+ 知识点 + 参考资料。

/// 一级分类。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct TopCategory {
  /// 分类 key。
  pub key: &'static str,
  /// 名称。
  pub name: &'static str,
  /// 描述。
  pub desc: &'static str,
  /// 标识色。
  pub color: &'static str,
}

/// 二级分类。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SubCategory {
  /// 官方分类码 P。
  pub code: &'static str,
  /// 所属一级分类 key。
  pub top: &'static str,
  /// 子类名称。
  pub name: &'static str,
}

/// 参考资料类型。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RefKind {
  /// 法条。
  Law,
  /// 资料。
  Material,
}

impl RefKind {
  /// 中文标签。
  #[must_use]
  pub const fn label(self) -> &'static str {
    match self {
      Self::Law => "法条",
      Self::Material => "资料",
    }
  }
}

/// 参考资料。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct RefItem {
  /// 类型。
  pub kind: RefKind,
  /// 文本。
  pub text: &'static str,
  /// 链接。
  pub url: Option<&'static str>,
}

const fn top(
  key: &'static str,
  name: &'static str,
  desc: &'static str,
  color: &'static str,
) -> TopCategory {
  TopCategory {
    key,
    name,
    desc,
    color,
  }
}

const fn sub(code: &'static str, top: &'static str, name: &'static str) -> SubCategory {
  SubCategory { code, top, name }
}

const fn law(text: &'static str, url: Option<&'static str>) -> RefItem {
  RefItem {
    kind: RefKind::Law,
    text,
    url,
  }
}

const fn mat(text: &'static str, url: Option<&'static str>) -> RefItem {
  RefItem {
    kind: RefKind::Material,
    text,
    url,
  }
}

