#[cfg(test)]
mod tests {
  use super::*;

  #[test]
  fn all_sections_are_populated() {
    assert_eq!(MONITORING_STEPS.len(), 8, "查处流程八步");
    assert!(!RR_STRUCTURE.is_empty());
    assert!(!SHARING_RULES.is_empty());
    assert!(!ASSIGNMENT_FLOW.is_empty());
    for list in [
      MONITORING_STEPS,
      RR_STRUCTURE,
      SHARING_RULES,
      ASSIGNMENT_FLOW,
    ] {
      for (title, text) in list {
        assert!(!title.is_empty() && !text.is_empty());
      }
    }
  }

  #[test]
  fn every_article_citation_points_to_a_real_article() {
    // 流程里引用的《条例》条文必须真的存在（本仓有全文，`find_refs` 只认存在的条号）。
    for (_, text) in MONITORING_STEPS.iter().chain(ASSIGNMENT_FLOW.iter()) {
      for r in crate::radio_law::find_refs(text) {
        assert!(
          crate::radio_law::article(r.law, r.number).is_some(),
          "引用不存在：{} 第{}条（{text}）",
          r.law,
          r.number
        );
      }
    }
  }

  #[test]
  fn the_regulation_citations_actually_resolve_to_the_regulation() {
    // 流程里的条例引用不能解析到别的法律上去。
    let text = MONITORING_STEPS[0].1;
    let refs = crate::radio_law::find_refs(text);
    assert_eq!(refs.len(), 1, "{text}");
    assert_eq!(refs[0].number, 56);
  }
}
