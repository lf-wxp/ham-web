  fn core(part: &str) -> &'static Core {
    core_by_part(part).expect("磁环库里应有这个料号")
  }

  fn m(id: &str) -> &'static Material {
    material(id).expect("应收录这个材料")
  }

  /// 官方 CSV 里直接读出的几行（不经过插值）：表点上插值必须原样返回。
  #[test]
  fn tabulated_points_come_back_exactly() {
    // 43：`10000,816.0434106,10.11279513` / `1000000,851.3550816,48`。
    assert_eq!(m("43").complex_mu(10_000.0), Some((816.043, 10.113)));
    assert_eq!(m("43").complex_mu(1_000_000.0), Some((851.355, 48.0)));
    // 61：`1.00E+06,123.6254116,0.497453645`。
    assert_eq!(m("61").complex_mu(1_000_000.0), Some((123.625, 0.497)));
    // 末点（表的上沿）也要能取到，不能因为 `partition_point` 越界而返回 None。
    for mat in MATERIALS {
      let (_, hi) = mat.range_hz();
      let last = mat.table.last().unwrap();
      assert_eq!(mat.complex_mu(hi), Some((last.1, last.2)), "{}", mat.id);
    }
  }

  #[test]
  fn tables_are_well_formed() {
    for mat in MATERIALS {
      assert!(mat.table.len() > 100, "{}", mat.id);
      assert!(
        mat.table.windows(2).all(|w| w[0].0 < w[1].0),
        "{} 频率须严格升序",
        mat.id
      );
      assert!(
        mat
          .table
          .iter()
          .all(|&(f, mu_re, mu_im)| f > 0.0 && mu_re > 0.0 && mu_im >= 0.0),
        "{}：≤ 300 MHz 内 µ' 为正、µ'' 非负",
        mat.id
      );
      assert!(mat.table.last().unwrap().0 <= 3.0e8, "{}", mat.id);
      assert!(mat.source.starts_with("https://fair-rite.com/"));
    }
    assert_eq!(m("43").range_hz().0, 10_000.0);
    assert_eq!(m("61").range_hz().0, 1_000_000.0);
  }

  /// 表内插值夹在左右两个表点之间；表外不外推。
  #[test]
  fn interpolation_stays_between_neighbours_and_never_extrapolates() {
    let mat = m("43");
    for w in mat.table.windows(2) {
      let mid = (w[0].0 * w[1].0).sqrt(); // 对数中点
      let (re, im) = mat.complex_mu(mid).unwrap();
      let (lo_re, hi_re) = (w[0].1.min(w[1].1), w[0].1.max(w[1].1));
      let (lo_im, hi_im) = (w[0].2.min(w[1].2), w[0].2.max(w[1].2));
      assert!((lo_re - 1e-9..=hi_re + 1e-9).contains(&re), "µ' @ {mid}");
      assert!((lo_im - 1e-9..=hi_im + 1e-9).contains(&im), "µ'' @ {mid}");
    }
    assert_eq!(mat.complex_mu(9_999.0), None, "低于表下沿不外推");
    assert_eq!(mat.complex_mu(3.0e8 + 1e6), None, "高于表上沿不外推");
    assert_eq!(m("61").complex_mu(500_000.0), None, "61 号表从 1 MHz 起");
    for bad in [0.0, -1.0, f64::NAN, f64::INFINITY] {
      assert_eq!(mat.complex_mu(bad), None, "{bad}");
    }
  }

  /// 低频端的 µ' 要和磁环库里登记的 µi 对得上：数据表与 `toroid::CORES` 是两处独立录入。
  #[test]
  fn low_frequency_permeability_agrees_with_the_core_library() {
    // 只查铁氧体：粉芯没有表（见 `every_ferrite_core_in_the_library_has_a_material_table`）。
    for c in CORES.iter().filter(|c| !c.is_powder()) {
      let mat = m(c.material);
      let (f_lo, _) = mat.range_hz();
      let (mu_re, _) = mat.complex_mu(f_lo).unwrap();
      let off = (mu_re - c.mu_i).abs() / c.mu_i;
      assert!(
        off < 0.05,
        "{} {}：表 µ'={mu_re}，库 µi={}",
        c.part,
        c.material,
        c.mu_i
      );
    }
  }

  /// 10 kHz 下 N 匝的电抗应与厂商 AL 给出的电感一致（AL 有 ±20% 公差，页面口径是 10 kHz）；电阻可忽略。
  #[test]
  fn at_10_khz_the_reactance_matches_the_al_inductance() {
    for part in ["5943000301", "5943001101", "5943003801"] {
      let c = core(part);
      let n = 3.0;
      let z = choke_impedance(c, n, 10_000.0).unwrap();
      let x_from_al = 2.0 * std::f64::consts::PI * 10_000.0 * c.al_nh * 1.0e-9 * n * n;
      let off = (z.x_ohm - x_from_al).abs() / x_from_al;
      assert!(
        off < c.tolerance_pct / 100.0,
        "{part}: X={} vs AL→{x_from_al}",
        z.x_ohm
      );
      assert!(z.resistive_share() < 0.05, "{part}: 10 kHz 几乎纯电感");
    }
  }

