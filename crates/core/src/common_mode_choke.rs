/// 真空磁导率（H/m）。
const MU0: f64 = 4.0e-7 * std::f64::consts::PI;

/// 一种铁氧体材料的复磁导率表。
#[derive(Debug, Clone, Copy)]
pub struct Material {
  /// 厂商材料牌号（与 [`Core::material`] 对应）。
  pub id: &'static str,
  /// `(频率 Hz, µ', µ'')`，频率严格升序。
  pub table: &'static [(f64, f64, f64)],
  /// 数据下载地址。
  pub source: &'static str,
  /// 取回日期。
  pub fetched: &'static str,
}

/// 已收录的材料（见模块文档的数据出处）。
pub const MATERIALS: &[Material] = &[
  Material {
    id: "43",
    table: MU_43,
    source: "https://fair-rite.com/wp-content/uploads/2020/11/43-Material-publish.csv",
    fetched: "2026-11-10",
  },
  Material {
    id: "61",
    table: MU_61,
    source: "https://fair-rite.com/wp-content/uploads/2021/11/61-Material-Fair-Rite.csv",
    fetched: "2026-11-10",
  },
];

/// 按牌号查材料。
#[must_use]
pub fn material(id: &str) -> Option<&'static Material> {
  MATERIALS.iter().find(|m| m.id == id.trim())
}

/// 材料表里最旧的取回日期（`YYYY-MM-DD`），供 [`crate::staleness`] 登记「这份人工转录的外部数据多久没复核了」。
#[must_use]
pub fn oldest_fetched() -> Option<&'static str> {
  MATERIALS.iter().map(|m| m.fetched).min()
}

impl Material {
  /// 表覆盖的频率范围（Hz，含两端）。
  #[must_use]
  pub fn range_hz(&self) -> (f64, f64) {
    let first = self.table.first().map_or(0.0, |r| r.0);
    let last = self.table.last().map_or(0.0, |r| r.0);
    (first, last)
  }

  /// `f_hz` 处的复磁导率 `(µ', µ'')`：在表内按「频率取对数、数值线性」插值，
  /// 恰在表点上就是表里的值。**超出表范围返回 `None`，不外推。**
  #[must_use]
  pub fn complex_mu(&self, f_hz: f64) -> Option<(f64, f64)> {
    if !positive(f_hz) {
      return None;
    }
    let (lo, hi) = self.range_hz();
    if f_hz < lo || f_hz > hi {
      return None;
    }
    let i = self.table.partition_point(|r| r.0 <= f_hz);
    // `i` 是第一个 > f 的点；f 等于最后一个点时 i == len，取最后一对。
    let upper = i.min(self.table.len() - 1);
    let lower = upper.saturating_sub(1);
    let (f0, a0, b0) = self.table[lower];
    let (f1, a1, b1) = self.table[upper];
    if f1 <= f0 {
      return Some((a0, b0));
    }
    let t = ((f_hz.ln() - f0.ln()) / (f1.ln() - f0.ln())).clamp(0.0, 1.0);
    Some((a0 + t * (a1 - a0), b0 + t * (b1 - b0)))
  }
}

/// 串联阻抗 `Z = R + jX`（Ω）。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Impedance {
  pub r_ohm: f64,
  pub x_ohm: f64,
}

impl Impedance {
  /// 阻抗模。
  #[must_use]
  pub fn magnitude(&self) -> f64 {
    self.r_ohm.hypot(self.x_ohm)
  }

  /// 电阻占模的比例（0–1）。接近 1 说明它是在「吸收」共模电流；接近 0 说明主要是电感，只是在「挡」。
  #[must_use]
  pub fn resistive_share(&self) -> f64 {
    let m = self.magnitude();
    if m > 0.0 { self.r_ohm / m } else { 0.0 }
  }
}

/// 匝数上限。最大的库内磁环（FT-240）的窗口也绕不下几十匝，再大只会让 N² 把数字放大到毫无意义
/// （理想模型本来就不含杂散电容，匝数越多越偏离真实）。
pub const MAX_TURNS: f64 = 100.0;

/// 匝数是否可用：穿过中心孔的次数只能是 1 到 [`MAX_TURNS`] 的整数。
#[must_use]
pub fn valid_turns(turns: f64) -> bool {
  turns.is_finite() && turns.fract() == 0.0 && (1.0..=MAX_TURNS).contains(&turns)
}

/// N 匝绕在 `core` 上的串联阻抗；磁环没有尺寸 / 材料表、匝数或频率不合法、频率超出表范围为 `None`。
///
/// 匝数是穿过磁环中心孔的次数（同轴线直接穿过去算 1 匝），不是线的圈数除以二；
/// 只收 [`valid_turns`] 允许的整数。
#[must_use]
pub fn choke_impedance(core: &Core, turns: f64, f_hz: f64) -> Option<Impedance> {
  if !valid_turns(turns) || !positive(core.ae_cm2) || !positive(core.le_cm) {
    return None;
  }
  let (mu_re, mu_im) = material(core.material)?.complex_mu(f_hz)?;
  let l0 = MU0 * turns * turns * (core.ae_cm2 * 1.0e-4) / (core.le_cm * 1.0e-2);
  let omega = 2.0 * std::f64::consts::PI * f_hz;
  Some(Impedance {
    r_ohm: omega * l0 * mu_im,
    x_ohm: omega * l0 * mu_re,
  })
}

/// 把 `z` 串进阻值 `loop_ohm` 的纯电阻回路里的插入损耗（dB，正数 = 衰减）；回路阻抗不是正数为 `None`。
#[must_use]
pub fn insertion_loss_db(z: &Impedance, loop_ohm: f64) -> Option<f64> {
  if !positive(loop_ohm) {
    return None;
  }
  Some(20.0 * ((loop_ohm + z.r_ohm).hypot(z.x_ohm) / loop_ohm).log10())
}

/// 表里一个波段的结果。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct BandRow {
  pub band: &'static str,
  /// 波段中心频率（MHz，取 [`AMATEUR_BAND_EDGES`] 上下沿的中点）。
  pub f_mhz: f64,
  /// 材料表覆盖不到这个频率（例如 61 号材料表从 1 MHz 起，不含 160 m 以下）时为 `None`。
  pub z: Option<Impedance>,
  pub loss_db: Option<f64>,
}

/// 160 m–6 m 各波段（以中心频率代表）的阻抗与插入损耗。
///
/// 只列 1.8–54 MHz：2 m 及以上绕了线的磁环匝间电容早已主导，理想电感性模型不再可信；
/// 2200 m / 630 m 的磁环做共模扼流不现实（要的匝数与体积都不合适）。
#[must_use]
pub fn band_rows(core: &Core, turns: f64, loop_ohm: f64) -> Vec<BandRow> {
  AMATEUR_BAND_EDGES
    .iter()
    .filter(|(_, lo, hi)| *lo >= 1.8 && *hi <= 54.0)
    .map(|&(band, lo, hi)| {
      let f_mhz = (lo + hi) / 2.0;
      let z = choke_impedance(core, turns, f_mhz * 1.0e6);
      let loss_db = z.and_then(|z| insertion_loss_db(&z, loop_ohm));
      BandRow {
        band,
        f_mhz,
        z,
        loss_db,
      }
    })
    .collect()
}

