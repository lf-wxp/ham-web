//! 铁氧体共模扼流圈：由磁环 + 匝数估算各业余波段的串联阻抗与插入损耗。
//!
//! 馈线上套磁环（`FT-240-43` 之类）是 HF 台站最常见的 RFI 对策，但磁环的作用不是它的低频电感
//! （[`crate::toroid`] 的 `AL` 是 10 kHz 下测的）：铁氧体在 HF 的复磁导率 `µ = µ' − jµ''` 里，
//! `µ''` 代表损耗，随频率先升后降；共模扼流要的正是这一份「损耗」，把共模电流变成热。绕 N 匝后：
//!
//! ```text
//! L0 = µ0 · N² · Ae / le                    （µr = 1 时的电感）
//! Z  = jωL0 · (µ' − jµ'') = ωL0·µ'' + j·ωL0·µ'
//!      └─ 电阻部分 R ──┘   └─ 电抗部分 X ──┘
//! ```
//!
//! 插入损耗按「共模回路是一个纯电阻 `R_loop`、扼流圈串在回路里」算：
//! `IL = 20·log10(|R_loop + Z| / R_loop)`。回路阻抗实际未知（取决于天线、馈线长度与接地），
//! 页面让用户自己填；默认 50 Ω 只是厂商的标准测量口径，不是你的共模回路。
//!
//! # 数据出处
//!
//! 复磁导率表来自 Fair-Rite 官方零件页「Complex Permeability vs. Frequency (CSV)」下载（2026-11-10 取回）：
//!
//! - 43 号材料：`https://fair-rite.com/wp-content/uploads/2020/11/43-Material-publish.csv`，
//!   10 kHz–3 GHz，HP4284A（10 kHz–1 MHz）与 E4991A（1 MHz–3 GHz）测得；
//! - 61 号材料：`https://fair-rite.com/wp-content/uploads/2021/11/61-Material-Fair-Rite.csv`，1 MHz–1.8 GHz。
//!
//! 这里**只嵌入 ≤ 300 MHz 的点**（数值四舍五入到 0.001，频率取整到 1 Hz，别的没动）：43 号材料的 `µ'`
//! 在 332 MHz 附近过零、61 号在 633 MHz，那一段是材料的尺寸谐振与测试夹具的影响，
//! 绕了线的磁环在远低于这些频率时就已被匝间电容主导。表里 `µ''` 全为正，`µ'` 在 ≤ 300 MHz 内全为正（单测断言）。
//!
//! # 精度边界（先读这个）
//!
//! - **不含匝间 / 对地杂散电容**：真实扼流圈的阻抗会在某个自谐振频率之后随频率*下降*，
//!   匝数越多、磁环越大谐振越低。这里算的是「理想电感性绕组」，所以高频端、大匝数时**偏高**。
//!   自谐振点依赖绕法与线径，没有可对拍的来源，本模块不给；实用上 HF 扼流圈常用 5–12 匝，匝数过多反而更差；
//! - 复磁导率是**小信号、25 °C、无直流偏置**下测的；大功率下磁通密度与温度都会改变 `µ`，
//!   厂商的阻抗曲线也不代表你的功率电平；
//! - 磁环库 [`crate::toroid::CORES`] 里只有 Fair-Rite 的 43 与 61 两种材料，其余材料没有表就不算；
//! - 插入损耗对回路阻抗很敏感（见上），只能当作量级参考，不是 EMC 认证数据。

