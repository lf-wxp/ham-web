  #[test]
  fn insertion_loss_matches_closed_form_cases() {
    // 纯电阻 450 Ω 串进 50 Ω 回路：20·log10(500/50) = 20 dB。
    let r = Impedance {
      r_ohm: 450.0,
      x_ohm: 0.0,
    };
    assert!((insertion_loss_db(&r, 50.0).unwrap() - 20.0).abs() < 1e-9);
    // 纯电抗 j50 串进 50 Ω：|50 + j50| / 50 = √2 → 3.0103 dB。
    let x = Impedance {
      r_ohm: 0.0,
      x_ohm: 50.0,
    };
    assert!((insertion_loss_db(&x, 50.0).unwrap() - 3.010_299_956_6).abs() < 1e-6);
    // 没有阻抗就没有损耗。
    let none = Impedance {
      r_ohm: 0.0,
      x_ohm: 0.0,
    };
    assert_eq!(insertion_loss_db(&none, 50.0), Some(0.0));
    for bad in [0.0, -50.0, f64::NAN] {
      assert_eq!(insertion_loss_db(&r, bad), None);
    }
    // 对拍独立脚本：FT-240-43、10 匝、7.1 MHz，50 Ω 回路 36.76 dB，200 Ω 回路 24.99 dB。
    let z = choke_impedance(core("5943003801"), 10.0, 7.1e6).unwrap();
    assert!((insertion_loss_db(&z, 50.0).unwrap() - 36.7613).abs() < 0.001);
    assert!((insertion_loss_db(&z, 200.0).unwrap() - 24.9901).abs() < 0.001);
  }

