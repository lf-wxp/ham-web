/// 多普勒补偿策略。
pub const DOPPLER_TIPS: &[&str] = &[
  "过境接近（AOS）时卫星靠近，接收到的下行频率偏高，需把接收频率向上微调（约 +3～5 kHz）。",
  "过境最高点（TCA）多普勒归零，使用标称频率。",
  "过境远离（LOS）时卫星远离，接收到的下行频率偏低，需把接收频率向下微调。",
  "补偿方向对上行与下行相反：跟踪下行时按上述方向调整，若固定下行于标称（调上行）则方向相反；FM 卫星只需 ±3～5 kHz，线性转发器需全程跟踪上下行。",
];

