//! LoRa / Meshtastic / AREDN：三种「数据网络」技术的入门与国内合规口径。
//!
//! 三者都在「数字通信」这条线上，但法律身份完全不同：
//! - LoRa 是调制技术（CSS 线性调频扩频）；
//! - Meshtastic 是基于 LoRa 的开源网状网，多工作在**免执照的微功率频段**；
//! - AREDN 是**业余**高速数据网，工作在业余频段、需要执照。
//!
//! 合规数字以工信部现行规定为准（470–510 MHz ≤ 50 mW 有工信部 2019 年 52 号公告口径）。

