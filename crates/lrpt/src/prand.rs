#[cfg(test)]
mod tests {
  use super::PRAND;

  #[test]
  fn table_is_the_ccsds_lfsr_sequence() {
    // 种子 = 表的前 8 位（全 1），递推出整张表。逐位一致说明它确实是这个 LFSR 的输出，而不是
    // 一张「只能照抄」的魔法表；任何转写错误（漏一个字节、抄错一位）都会让后面全部错位。
    let bits: Vec<u8> = PRAND
      .iter()
      .flat_map(|b| (0..8).rev().map(move |i| (b >> i) & 1))
      .collect();
    assert_eq!(&bits[..8], &[1; 8], "种子应是全 1");
    let mut s = bits[..8].to_vec();
    while s.len() < bits.len() {
      let n = s.len();
      s.push(s[n - 1] ^ s[n - 3] ^ s[n - 5] ^ s[n - 8]);
    }
    assert_eq!(s, bits);
  }

  #[test]
  fn the_bit_stream_has_period_255() {
    let bits: Vec<u8> = PRAND
      .iter()
      .flat_map(|b| (0..8).rev().map(move |i| (b >> i) & 1))
      .collect();
    assert!(bits.iter().enumerate().all(|(i, &b)| b == bits[i % 255]));
    // 且 255 不能再被缩短（本原多项式 → 最大周期）。
    assert!((1..255).all(|p| (0..bits.len() - p).any(|i| bits[i] != bits[i + p])));
  }
}
