function hellWav(text: string): Buffer {
  const RATE = 8000;
  const CARRIER = 980;
  // 像素边界按理想位置取整：8000 / 122.5 = 65.31，取整成固定 65 会让「真实」像素率变成
  // 123.08 Hz——合成出来的信号本身就是错的（解码端按理想边界切分，累计漂移会越差越多）。
  const edge = (i: number): number => Math.round((i * RATE) / 122.5);
  const samples: number[] = [];
  let index = 0;
  for (const ch of text.toUpperCase()) {
    const rows = FONT[ch];
    if (!rows) continue;
    // 5 列 → 7 字节（bit 0 = 底行）。
    const cols = [0, 0, 0, 0, 0];
    for (let c = 0; c < 5; c += 1) {
      for (let r = 0; r < 7; r += 1) {
        if (rows[r][c] === "#") cols[c] |= 1 << (6 - r);
      }
    }
    const g = [0, cols[0], cols[1], cols[2], cols[3], cols[4], 0];
    for (const col of g) {
      for (let row = 0; row < 7; row += 1) {
        const on = (col >> row) & 1;
        const start = edge(index);
        const end = Math.max(edge(index + 1), start + 1);
        index += 1;
        for (let i = start; i < end; i += 1) {
          const t = i / RATE;
          samples.push(on ? Math.sin(2 * Math.PI * CARRIER * t) * 0.5 : 0);
        }
      }
    }
  }

  const dataLen = samples.length * 2;
  const out = Buffer.alloc(44 + dataLen);
  out.write("RIFF", 0);
  out.writeUInt32LE(36 + dataLen, 4);
  out.write("WAVEfmt ", 8);
  out.writeUInt32LE(16, 16);
  out.writeUInt16LE(1, 20);
  out.writeUInt16LE(1, 22);
  out.writeUInt32LE(RATE, 24);
  out.writeUInt32LE(RATE * 2, 28);
  out.writeUInt16LE(2, 32);
  out.writeUInt16LE(16, 34);
  out.write("data", 36);
  out.writeUInt32LE(dataLen, 40);
  samples.forEach((s, i) => out.writeInt16LE(Math.round(s * 32767), 44 + i * 2));
  return out;
}

test("Feld Hell 解码：上传合成录音，解码出原文", async ({ page }) => {
  await page.goto("/hell-decode");
  await expect(page.getByRole("heading", { name: "Feld Hell 解码器" })).toBeVisible();

  await page.setInputFiles('input[type="file"]', {
    name: "cq.wav",
    mimeType: "audio/wav",
    buffer: hellWav("CQ DE BG1AAA"),
  });

  // Worker 后台解码后还原原文。wasm 首次加载较慢，显式放宽到 30s。
  await expect(page.getByText("CQ DE BG1AAA")).toBeVisible({ timeout: 30000 });
  await expect(page.getByRole("button", { name: "解码其他文件" })).toBeVisible();
});

test("Feld Hell 解码：坏样本给出错误提示而非空白", async ({ page }) => {
  await page.goto("/hell-decode");
  await page.setInputFiles('input[type="file"]', {
    name: "empty.wav",
    mimeType: "audio/wav",
    buffer: hellWav("").subarray(0, 44), // 只有 WAV 头
  });
  await expect(page.getByText("解码失败").first()).toBeVisible();
});
